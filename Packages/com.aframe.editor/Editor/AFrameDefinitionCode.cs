using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using UnityEditor;
using UnityEditor.Compilation;

namespace AFrame.Editor
{
    internal static class AFrameDefinitionCode
    {
        private const string FileName = "AFrameDefinitionIds.g.cs";
        private const string Link = "Assets/Game/Composition/Generated/link.xml";

        internal static Dictionary<string, string> Render(IEnumerable<AFrameDefinitionImporter.Source> sources,
            Action<string, string> issue)
        {
            var result = new Dictionary<string, string>(StringComparer.Ordinal);
            var contracts = CompilationPipeline.GetAssemblies()
                .Select(assembly => new { assembly.name,
                    path = CompilationPipeline.GetAssemblyDefinitionFilePathFromAssemblyName(assembly.name) })
                .Where(item => item.name.EndsWith(".Contracts", StringComparison.Ordinal)
                    && AFrameArchitectureValidator.IsAFrameAssembly(item.path))
                .OrderBy(item => item.name, StringComparer.Ordinal).ToArray();
            if (contracts.Length != 0)
                result.Add(Link, "<!-- Generated by AFrame. -->\n" + new XElement("linker",
                    contracts.Select(item => new XElement("assembly", new XAttribute("fullname", item.name),
                        new XAttribute("preserve", "all")))).ToString().Replace("\r\n", "\n") + "\n");

            foreach (var group in sources.GroupBy(source => source.Model.Assembly.GetName().Name, StringComparer.Ordinal))
            {
                var contract = contracts.SingleOrDefault(item => item.name == group.Key);
                if (contract == null)
                {
                    foreach (var source in group)
                        issue(source.Path, "Definition types must be declared in an AFrame Contracts assembly.");
                    continue;
                }

                var directory = Path.GetDirectoryName(contract.path).Replace('\\', '/');
                var path = directory + "/Generated/" + FileName;
                var namespaceName = group.Key.Substring(0, group.Key.Length - ".Contracts".Length);
                if (!Regex.IsMatch(namespaceName, @"\A[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*\z"))
                {
                    issue(contract.path, "Contracts assembly name must form a valid namespace for generated IDs.");
                    continue;
                }

                var names = new HashSet<string>(StringComparer.Ordinal);
                var fields = new List<string>();
                foreach (var source in group.OrderBy(source => source.Header.id, StringComparer.Ordinal))
                {
                    var name = string.Concat(Regex.Split(source.Header.id, "[._-]")
                        .Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
                    if (char.IsDigit(name[0]))
                        name = "Id" + name;
                    if (!names.Add(name))
                        issue(source.Path, $"Generated definition constant '{name}' is already in use.");
                    else
                        fields.Add($"        public const string {name} = \"{source.Header.id}\";");
                }

                result.Add(path, "// Generated by AFrame.\n" + $"namespace {namespaceName}\n{{\n"
                    + "    public static class DefinitionIds\n    {\n" + string.Join("\n", fields)
                    + "\n    }\n}\n");
            }
            return result;
        }

        internal static IEnumerable<string> Stale(Dictionary<string, string> expected)
        {
            foreach (var artifact in expected)
                if (!File.Exists(artifact.Key) || File.ReadAllText(artifact.Key) != artifact.Value)
                    yield return artifact.Key;
            foreach (var path in Existing().Where(path => !expected.ContainsKey(path)))
                yield return path;
        }

        internal static void Publish(Dictionary<string, string> expected)
        {
            var obsolete = Existing().Where(path => !expected.ContainsKey(path)).ToArray();
            foreach (var artifact in expected)
            {
                if (File.Exists(artifact.Key) && File.ReadAllText(artifact.Key) == artifact.Value)
                    continue;
                Directory.CreateDirectory(Path.GetDirectoryName(artifact.Key));
                File.WriteAllText(artifact.Key, artifact.Value);
                AssetDatabase.ImportAsset(artifact.Key);
            }
            foreach (var path in obsolete)
                AssetDatabase.DeleteAsset(path);
        }

        private static IEnumerable<string> Existing()
        {
            if (File.Exists(Link))
                yield return Link;
            if (!Directory.Exists("Assets/Game/Features"))
                yield break;
            foreach (var path in Directory.GetFiles("Assets/Game/Features", FileName, SearchOption.AllDirectories))
                yield return path.Replace('\\', '/');
        }
    }
}
